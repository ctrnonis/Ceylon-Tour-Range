export function getAttraction(slug: string): Attraction | undefined {
  return attractions.find((attraction) => attraction.slug === slug);
}

/** Featured on the homepage. */
export const featuredAttractions = ["sigiriya-rock-fortress", "nine-arch-bridge", "galle-fort"]
  .map(getAttraction)
  .filter((attraction): attraction is Attraction => Boolean(attraction));

/** Other attractions in the same town, for "nearby" suggestions. */
export function attractionsNear(location: Attraction["location"], excludeSlug?: string): Attraction[] {
  return attractions.filter((attraction) => attraction.location === location && attraction.slug !== excludeSlug);
}
